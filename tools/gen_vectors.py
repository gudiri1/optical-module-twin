#!/usr/bin/env python3
"""Generate CMIS conformance vectors from the module twin.

Each scenario drives the simulated module into a state (nominal, fiber cut,
laser end of life, hot case, module fault, low power, 4x100G breakout),
captures Lower Memory and Pages 00h/01h/02h/11h in one snapshot, and records
the values the independent Python decoder (host/omt/cmis.py) reads from those
bytes. Outputs:

  <out>/cmis_vectors.h     C header for host stacks (Zephyr ztest included)
  <out>/cmis_vectors.json  same data for any other language

Usage: python3 tools/gen_vectors.py build/vectors
"""
from __future__ import annotations

import json
import math
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "host"))

from omt import cmis  # noqa: E402
from omt.host import CmisHost  # noqa: E402
from omt.sim import SimModule  # noqa: E402

PAGES = (0x00, 0x01, 0x02, 0x11)


def _up(seed=7, appsel=1):
    m = SimModule(seed=seed)
    h = CmisHost(m)
    h.bring_up(appsel=appsel)
    m.run(3000)
    h.read_flags()
    return m, h


def scenarios():
    m, h = _up()
    yield "nominal_400g", "400GBASE-DR4, all lanes active, no flags", m, h

    m, h = _up()
    m.set("rx_dbm.2", -40)
    m.run(500)
    yield "fiber_cut_lane3", "Rx LOS, Rx CDR LOL and Rx power alarms on media lane 3", m, h

    m, h = _up()
    m.set("aging.1", 3.0)
    m.run(3000)
    yield "laser_eol_lane2", "laser end of life on media lane 2: TxFault, Tx power low", m, h

    m, h = _up()
    m.set("case_temp", 76)
    m.set("vcc", 3.10)
    m.run(150000)
    yield "hot_low_vcc", "case 76 C and Vcc 3.10 V: temperature high and Vcc low warnings", m, h

    m, h = _up()
    m.set("case_temp", 95)
    m.run(150000)
    yield "module_fault", "module over-temperature: ModuleFault, lanes deactivated", m, h

    m = SimModule(seed=7)
    h = CmisHost(m)
    yield "low_power", "after reset: ModuleLowPwr, ModuleStateChanged latched", m, h

    m, h = _up(appsel=2)
    yield "breakout_4x100g", "AppSel 2: four 100GBASE-DR data paths", m, h


def _mdeg(c):
    return int(c * 1000)  # truncation toward zero, like integer C code


def expected(img: cmis.CmisImage) -> dict:
    lo = cmis.decode_lower(img.lower)
    p0 = cmis.decode_page00(img.pages[0x00])
    p2 = cmis.decode_page02(img.pages[0x02])
    p11 = cmis.decode_page11(img.pages[0x11], media_lanes=8)
    flags9 = img.lower[9]
    b160 = img.pages[0x01][160 - 128]
    mult = 1 << ((b160 >> 3) & 3)
    lanes = []
    for i in range(8):
        ln = p11["lanes"][i]
        bits = sum(1 << (off - 134) for off, name in cmis.P11_FLAGS.items() if name in ln["flags"])
        dp = (img.pages[0x11][(i // 2)] >> (4 * (i & 1))) & 0xF
        lanes.append({"dp_state": dp, "tx_power_nw": round(ln["tx_power_uw"] * 1000),
                      "tx_bias_ua": round(ln["tx_bias_ma"] * 1000) * mult,
                      "rx_power_nw": round(ln["rx_power_uw"] * 1000), "flags": bits})

    def thr(d, scale, conv=round):
        return [conv(d[k] * scale) for k in ("high_alarm", "low_alarm", "high_warning", "low_warning")]

    return {
        "identifier": lo["identifier_code"], "module_state": lo["module_state_code"],
        "power_class": p0["power_class"], "max_power_mw": round(p0["max_power_w"] * 1000),
        "vendor_pn": p0["vendor_pn"], "vendor_sn": p0["vendor_sn"],
        "temp_mdegc": _mdeg(lo["temperature_c"]), "vcc_uv": round(lo["vcc_v"] * 1e6),
        "monitor_flags": flags9, "tx_bias_multiplier": mult,
        "thr_temp_mdegc": thr(p2["temp_c"], 1000, int), "thr_vcc_uv": thr(p2["vcc_v"], 1e6),
        "thr_tx_power_nw": thr(p2["tx_power_uw"], 1000), "thr_tx_bias_ua": [x * mult for x in thr(p2["tx_bias_ma"], 1000)],
        "thr_rx_power_nw": thr(p2["rx_power_uw"], 1000),
        "lanes": lanes,
    }


def _carr(b: bytes) -> str:
    rows = [", ".join(f"0x{x:02X}" for x in b[i:i + 12]) for i in range(0, len(b), 12)]
    return "{\n\t\t" + ",\n\t\t".join(rows) + "}"


def main(out: str):
    outp = Path(out)
    outp.mkdir(parents=True, exist_ok=True)
    vecs = []
    for name, desc, m, h in scenarios():
        lower = h.lower()
        img = cmis.CmisImage(lower, {p: h.upper(p) for p in PAGES})
        vecs.append({"name": name, "description": desc, "lower": img.lower.hex(),
                     "pages": {f"{p:02X}": img.pages[p].hex() for p in PAGES},
                     "expected": expected(img)})
        m.close()
    (outp / "cmis_vectors.json").write_text(json.dumps(vecs, indent=1))

    h = ["/* Generated by tools/gen_vectors.py from the Optical Module Twin. Do not edit. */",
         "/* SPDX-License-Identifier: Apache-2.0 */", "#include <stdint.h>", "",
         "struct cmis_vector_lane {", "\tuint8_t dp_state;", "\tuint32_t tx_power_nw;",
         "\tuint32_t tx_bias_ua;", "\tuint32_t rx_power_nw;", "\tuint32_t flags;", "};", "",
         "struct cmis_vector {", "\tconst char *name;", "\tconst char *description;",
         "\tuint8_t lower[128];", "\tuint8_t page00[128];", "\tuint8_t page01[128];",
         "\tuint8_t page02[128];", "\tuint8_t page11[128];",
         "\tuint8_t identifier, module_state, power_class, monitor_flags, tx_bias_multiplier;",
         "\tuint16_t max_power_mw;", "\tconst char *vendor_pn;", "\tconst char *vendor_sn;",
         "\tint32_t temp_mdegc;", "\tuint32_t vcc_uv;",
         "\tint32_t thr_temp_mdegc[4], thr_vcc_uv[4], thr_tx_power_nw[4], thr_tx_bias_ua[4],"
         " thr_rx_power_nw[4];",
         "\tstruct cmis_vector_lane lanes[8];", "};", "",
         "static const struct cmis_vector cmis_vectors[] = {"]
    for v in vecs:
        e = v["expected"]
        pg = {k: bytes.fromhex(x) for k, x in v["pages"].items()}
        lanes = ", ".join("{%d, %du, %du, %du, 0x%xu}" % (ln["dp_state"], ln["tx_power_nw"], ln["tx_bias_ua"],
                                                             ln["rx_power_nw"], ln["flags"]) for ln in e["lanes"])
        h += ["\t{", f'\t\t.name = "{v["name"]}",', f'\t\t.description = "{v["description"]}",',
              f"\t\t.lower = {_carr(bytes.fromhex(v['lower']))},",
              f"\t\t.page00 = {_carr(pg['00'])},", f"\t\t.page01 = {_carr(pg['01'])},",
              f"\t\t.page02 = {_carr(pg['02'])},", f"\t\t.page11 = {_carr(pg['11'])},",
              f"\t\t.identifier = {e['identifier']}, .module_state = {e['module_state']},"
              f" .power_class = {e['power_class']}, .monitor_flags = 0x{e['monitor_flags']:02X},"
              f" .tx_bias_multiplier = {e['tx_bias_multiplier']},",
              f"\t\t.max_power_mw = {e['max_power_mw']},",
              f'\t\t.vendor_pn = "{e["vendor_pn"]}", .vendor_sn = "{e["vendor_sn"]}",',
              f"\t\t.temp_mdegc = {e['temp_mdegc']}, .vcc_uv = {e['vcc_uv']},"]
        for k in ("thr_temp_mdegc", "thr_vcc_uv", "thr_tx_power_nw", "thr_tx_bias_ua", "thr_rx_power_nw"):
            h.append(f"\t\t.{k} = {{{', '.join(str(int(x)) for x in e[k])}}},")
        h += [f"\t\t.lanes = {{{lanes}}},", "\t},"]
    h += ["};", ""]
    (outp / "cmis_vectors.h").write_text("\n".join(h))
    print(f"wrote {len(vecs)} vectors to {outp}")


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else str(ROOT / "build" / "vectors"))
